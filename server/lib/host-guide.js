/**
 * 원격(다른 기계) 워커에게 붙는 제약 안내.
 *
 * 머신이 다르면 워킹트리도 파일 임대도 공유되지 않는다. 이 안내 없이 원격 워커를
 * 돌리면 "고친 파일 경로" 만 회신해 놓고 origin 쪽에는 그 파일이 없는 상태가 된다.
 * `buildTierGuide` 와 같은 자리에서 위임 task 에 자동 주입된다.
 */
export function buildHostGuide({ selfId, remoteId, remoteLabel = null } = {}) {
  const where = remoteLabel ? `${remoteLabel} (\`${remoteId}\`)` : `\`${remoteId}\``;
  return (
    `[원격 실행 — 다른 기계]\n` +
    `이 작업은 ${where} 인스턴스에서 실행됩니다. 위임을 건 쪽(\`${selfId}\`)과 **파일 시스템이 공유되지 않습니다.**\n` +
    `- 기계 간에는 파일 임대가 걸리지 않습니다. 상대 기계의 작업 중 파일을 알 수 없으니, 손대는 범위를 스스로 좁히세요.\n` +
    `- **결과는 커밋·푸시로만 전달됩니다.** 로컬 파일만 고치고 끝내면 리드는 그 변경을 볼 수 없습니다.\n` +
    `- 회신에는 푸시한 브랜치/커밋 해시를 반드시 적으세요. 절대경로만 적으면 리드 쪽에서 열리지 않습니다.\n` +
    `- 원격 세션 로그는 리드의 UI 에 보이지 않습니다. 판단에 필요한 내용은 회신 본문에 담으세요.`
  );
}
